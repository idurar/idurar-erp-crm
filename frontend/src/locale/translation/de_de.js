const countryNames = new Intl.DisplayNames(['de-DE'], { type: 'region' });
const normalizeKey = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-zA-Z0-9]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '');

const countryTranslations = Object.fromEntries(
  countryList
    .filter(({ value }) => /^[A-Z]{2}$/.test(value))
    .map(({ label, value }) => [normalizeKey(label), countryNames.of(value)])
);

